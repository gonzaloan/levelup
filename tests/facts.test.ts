// Do the design documents still describe the platform that ships?
//
// The characteristic failure of a design doc is a number that was true when it was
// typed. Two of the counts in facts.json were wrong on their first run — `it(` missed
// all 87 Playwright tests, and a field named `emptyAxes` counted every axes figure — and
// both would have been quoted in a document as evidence.
//
// So the docs are generated from facts.json (tools/gen-docs.cjs) and this file closes
// the loop twice: facts.json must agree with the source it claims to measure, and the
// generated docs must agree with facts.json.
import { describe, it, expect } from "vitest";

describe("the section 42 docs report what is NOT built", () => {
  // These docs describe systems that are mostly unimplemented, and the failure mode is a
  // document that restates the spec so the reader assumes it shipped. Each assertion
  // below pins a doc to an absence that facts.json measures — so if the feature is ever
  // built, the test fails and the doc has to be rewritten rather than silently becoming
  // wrong in the flattering direction.
  const read = (f: string) => readFileSync(`${DOCS}/${f}`, "utf8");
  const sys = facts.systems;

  it("saved-content-model.md says the feature does not exist", () => {
    expect(sys.savedContent.exists, "saved content now exists — rewrite the doc").toBe(false);
    expect(read("saved-content-model.md")).toContain("**Not built.**");
  });

  it("interview-mode.md says there is no interview route", () => {
    expect(sys.interviewMode.routeExists, "an interview surface now exists — rewrite the doc").toBe(false);
    const body = read("interview-mode.md");
    expect(body).toContain("the product surface does not");
  });

  it("the retention docs report the real number of queue sources", () => {
    const built = Object.values(sys.reviewQueue.sources).filter(Boolean).length;
    expect(sys.reviewQueue.sourcesImplemented).toBe(built);
    // The correction that matters: the first detectors reported 3 of 8 by matching
    // /prerequisite/ (a gate on what comes NEXT) and by probing dueConcepts twice.
    expect(read("retention-engine.md"), "the queue source count is stale")
      .toContain(`## The queue: ${built} of ${sys.reviewQueue.sourcesSpecified} sources`);
    expect(read("review-queue-model.md"))
      .toContain(`is ${built} of ${sys.reviewQueue.sourcesSpecified}`);
  });

  it("engagement-model.md admits confidence is not read by the scheduler", () => {
    // Captured, and used for the band cap and calibration gap — but not for scheduling,
    // which is where section 33 wants it. A doc that said "confidence-aware" would be
    // defensible-sounding and wrong.
    expect(sys.confidence.captured).toBe(true);
    expect(sys.confidence.usedForBandCap).toBe(true);
    expect(sys.confidence.usedByReviewQueue, "the scheduler now reads confidence — rewrite the doc").toBe(false);
    expect(read("engagement-model.md")).toMatch(/the review scheduler never reads it/);
  });

  it("the inventory-backed docs agree with the generated inventories", () => {
    const bank = JSON.parse(readFileSync(`${DOCS}/question-bank.json`, "utf8"));
    const ib = JSON.parse(readFileSync(`${DOCS}/interview-bank.json`, "utf8"));
    const ce = JSON.parse(readFileSync(`${DOCS}/code-example-inventory.json`, "utf8"));
    expect(read("question-bank-audit.md"), "the item count is stale").toContain(`${bank.items.length} items`);
    expect(read("evaluation-system.md")).toContain(`${bank.items.length} scored items`);
    expect(read("code-example-policy.md")).toContain(`${ce.examples.length} snippets`);
    const usable = ib.tracks.reduce((a: number, t: { usableItems: number }) => a + t.usableItems, 0);
    expect(read("interview-question-audit.md"), "the usable-item total is stale")
      .toContain(`Total usable: ${usable}`);
  });

  it("aws-architecture-standard.md reports the unpinned services rather than implying none", () => {
    const a = JSON.parse(readFileSync(`${DOCS}/aws-architecture-inventory.json`, "utf8"));
    const unpinned = [...new Set(a.claims.flatMap((x: { unpinnedServices: string[] }) => x.unpinnedServices))];
    const body = read("aws-architecture-standard.md");
    expect(body).toContain(`${a.claims.length} AWS claims`);
    expect(body, "the doc does not state how many services are unpinned")
      .toContain(`${unpinned.length} named services are **not** pinned`);
  });

  it("the work-package templates name the gaps in their own schemas", () => {
    // The architecture template must state which section 38.2 fields CodexArchitecture
    // cannot record, rather than quietly listing only the fields that exist.
    // Matched across a line wrap: the phrase breaks as "**absent from the\nschema**" in
    // the generated markdown, and a literal toContain failed on the newline while the
    // claim was already there. Asserting on formatting rather than meaning is how a
    // gate earns a reputation for crying wolf.
    expect(read("architecture-work-package-template.md").replace(/\s+/g, " "))
      .toContain("**absent from the schema**");
    expect(read("code-example-policy.md"), "the doc does not count its missing schema fields")
      .toMatch(/five of nine fields are absent/);
  });
});

describe("the generated docs agree with facts.json", () => {
  // The load-bearing assertion of this file. Each doc interpolates counts from
  // facts.json, so a doc regenerated from stale facts, or edited by hand, diverges here.
  const read = (f: string) => readFileSync(`${DOCS}/${f}`, "utf8");

  it("the learning model reports the real per-stage coverage", () => {
    const body = read("target-learning-model.md");
    const cov = facts.learningModel.coverage;
    for (const [stage, n] of Object.entries(cov) as [string, number][]) {
      const label = stage === "worked" ? "Worked example" : stage[0].toUpperCase() + stage.slice(1);
      const row = body.match(new RegExp(`\\*\\*${label}\\*\\*.*?\\|\\s*(\\d+)\\s*\\|`));
      expect(row, `${label} has no row in the stage table`).toBeTruthy();
      expect(Number(row![1]), `the ${label} count is stale`).toBe(n);
    }
  });

  it("the validation report's counts match the measured suite", () => {
    const body = read("validation-report.md");
    expect(body).toContain(`${facts.validation.unitTests}\nunit tests`);
    expect(body).toContain(`${facts.validation.e2eTests} browser tests`);
    expect(body).toContain(`${facts.validation.contentValidators} content`);
    for (const name of facts.validation.baselineNames as string[]) {
      expect(body, `${name} is not documented in the validation report`).toContain(name);
    }
  });

  it("the STATUS dashboard reports the live learning-model coverage", () => {
    const body = read("STATUS.md");
    for (const [stage, n] of Object.entries(facts.learningModel.coverage) as [string, number][]) {
      const label = stage === "worked" ? "worked example" : stage;
      // Parsed structurally rather than by regex. Building the pattern as a string put
      // this three levels of escaping deep — TS source, template literal, RegExp — and
      // the pipes and `\d` arrived unescaped, matching nothing and reporting NaN. Same
      // class as the backspace in gen-facts.cjs: stop needing the escape.
      const row = body
        .split(NL)
        .map((l) => l.split("|").map((cell) => cell.trim()))
        .find((cells) => cells[1] === label);
      expect(row, `${label} has no row in the STATUS table`).toBeTruthy();
      expect(Number(row![2]), `STATUS reports a stale ${label} count`).toBe(n);
    }
    expect(body, "STATUS misstates the validator count")
      .toContain(`**${facts.validation.contentValidators} content validators**`);
    expect(body, "STATUS misstates the check count").toContain(`**${facts.content.checks} checks**`);
  });

  it("the analytics plan states zero instrumentation", () => {
    const body = read("analytics-plan.md");
    expect(body).toContain(`**${facts.analytics.trackingCalls} tracking calls.**`);
    expect(body).toContain(`${facts.analytics.progressFields} fields`);
  });

  it("the accessibility audit's counts match the source scan", () => {
    const body = read("accessibility-audit.md");
    expect(body).toContain(`${facts.a11y.tsxFiles} TSX files`);
    expect(body).toContain(`${facts.a11y.imagesWithAlt}/${facts.a11y.imagesTotal}\` images`);
  });

  it("the visual audit's figure counts match the content", () => {
    const body = read("visual-asset-audit.md");
    expect(body).toContain(`${facts.visual.figures} authored figures`);
    for (const [kind, n] of Object.entries(facts.visual.byKind) as [string, number][]) {
      const row = body.match(new RegExp(`\\\`${kind}\\\` \\| (\\d+) \\|`));
      expect(row, `figure kind ${kind} has no row`).toBeTruthy();
      expect(Number(row![1]), `the ${kind} count is stale`).toBe(n);
    }
  });

  it("the migration map and rollout plan agree about the route model", () => {
    const laddered = (facts.routing.routeIds as string[]).filter((x) => x.includes("-")).length;
    for (const f of ["migration-map.md", "rollout-plan.md"]) {
      expect(read(f), `${f} misstates the route count`).toContain(`${laddered} routes`);
    }
    expect(read("migration-map.md")).toContain(`${facts.routing.pageRoutes} page routes`);
  });

  it("no generated doc claims a Predict or Build coverage it does not have", () => {
    // The specific dishonesty worth blocking: a doc that reads as though the engines
    // being built means the content exists.
    const gapPredict = facts.learningModel.totalConcepts - facts.learningModel.coverage.predict;
    const gapBuild = facts.learningModel.totalConcepts - facts.learningModel.coverage.build;
    for (const f of ["migration-map.md", "rollout-plan.md"]) {
      const body = read(f);
      expect(body, `${f} does not state the Predict gap`).toContain(`${gapPredict} concepts`);
      expect(body, `${f} does not state the Build gap`).toContain(`${gapBuild}`);
    }
  });
});

describe("facts.json agrees with the source it measures", () => {
  it("counts the content the app actually loads", () => {
    // Measured against the TypeScript modules, not by re-reading the JSON the generator
    // read. Re-parsing the same file would only prove JSON.parse is deterministic.
    expect(facts.content.spineConcepts).toBe(CONCEPTS.length);
    expect(facts.content.lessons).toBe(LESSONS.length);
    expect(facts.content.conceptLessons).toBe(CONCEPT_LESSONS.length);
    expect(facts.content.checkpoints).toBe(CHECKPOINTS.length);
    expect(facts.content.checkpointItems).toBe(CHECKPOINTS.reduce((a, c) => a + c.items.length, 0));
    expect(facts.content.checks).toBe(CHECKS.length);
    expect(facts.content.builds).toBe(BUILDS.length);
    expect(facts.content.domains).toBe(ORDERED_DOMAINS.length);
  });

  it("counts each check mechanic correctly", () => {
    const byKind: Record<string, number> = {};
    for (const k of CHECKS) byKind[k.kind] = (byKind[k.kind] ?? 0) + 1;
    expect(facts.content.checksByKind).toEqual(byKind);
  });

  it("measures the route model rather than restating it", () => {
    expect(facts.routing.stageCount).toBe(STAGES.length);
    for (const r of ROUTES) expect(facts.routing.routeIds).toContain(r.id);
  });

  it("the learning-stage coverage is derived from the content", () => {
    expect(facts.learningModel.coverage.predict)
      .toBe(CONCEPT_LESSONS.filter((c) => c.predict).length);
    expect(facts.learningModel.coverage.recall)
      .toBe(CONCEPT_LESSONS.filter((c) => c.flashcards?.length).length);
    expect(facts.learningModel.coverage.worked)
      .toBe(CONCEPT_LESSONS.filter((c) => c.example).length);
    expect(facts.learningModel.coverage.practice)
      .toBe(CONCEPT_LESSONS.filter((c) => CHECKS.some((k) => k.concept === c.slug)).length);
    expect(facts.learningModel.totalConcepts).toBe(CONCEPT_LESSONS.length);
  });

  it("reports Explain as absent, because it is", () => {
    // Explain needs free-text grading, which needs a server. This platform is a static
    // export with no API routes, so the stage is blocked by the deployment model rather
    // than by effort — see target-learning-model.md. If it is ever built, this test
    // SHOULD fail, which is the signal to rewrite that section.
    expect(facts.learningModel.coverage.explain, "Explain now exists — update the docs").toBe(0);
  });

  it("counts a Transfer item only when it is TAGGED as one", () => {
    // This test previously asserted `transfer: 0`, and six transfer items were already
    // shipping. Both were right: the items existed and nothing marked them, so no gate
    // could tell them from an ordinary check. `transferTo` is that mark.
    //
    // The assertion is derived from the content rather than restated, so authoring a
    // seventh item moves it without an edit here.
    const tagged = CHECKS.filter((k) => (k as { transferTo?: string }).transferTo);
    expect(tagged.length, "no check is tagged as a transfer item").toBeGreaterThan(0);
    const concepts = new Set(tagged.map((k) => k.concept));
    expect(facts.learningModel.coverage.transfer).toBe(concepts.size);
  });

  it("every Transfer item names a domain its concept genuinely relates to", () => {
    // The rule merge-checks.cjs enforces, asserted here too because it is the property
    // that keeps the coverage number meaningful. Without it, `transferTo` becomes a
    // free-text label meaning "this feels cross-domain".
    const domainOf = new Map(CONCEPTS.map((c) => [c.concept.slug, c.domainId]));
    const related = new Map<string, Set<string>>();
    for (const c of CONCEPTS) {
      for (const lean of c.concept.leansOn ?? []) {
        const target = domainOf.get(lean);
        if (!target || target === c.domainId) continue;
        if (!related.has(lean)) related.set(lean, new Set());
        related.get(lean)!.add(c.domainId);
      }
    }
    const bad: string[] = [];
    for (const k of CHECKS) {
      const to = (k as { transferTo?: string }).transferTo;
      if (!to) continue;
      if (to === domainOf.get(k.concept)) { bad.push(`${k.id}: transfers to its own domain`); continue; }
      if (!related.get(k.concept)?.has(to)) bad.push(`${k.id}: no leansOn edge to ${to}`);
    }
    expect(bad, "a transfer claim is unfounded").toEqual([]);
  });

  it("reports zero analytics, and would notice instrumentation appearing", () => {
    expect(facts.analytics.trackingCalls).toBe(0);
    expect(facts.analytics.fetchCallsToApi).toBe(0);
  });

  it("separates structural empty strings from missing translations", () => {
    // The naive count is 7 and every one is correct content: three cloze checks whose
    // sentence opens with a blank, and one deliberate `kind: "none"` figure opt-out.
    // Reporting "7 empty strings" would describe a translation gap that does not exist.
    expect(facts.i18n.emptyProse, "a real translation gap has appeared").toBe(0);
    expect(facts.i18n.emptyStructural).toBe(facts.i18n.structuralPaths.length);
    for (const p of facts.i18n.structuralPaths as string[]) {
      expect(p, `${p} is neither a cloze segment nor a none-diagram caption`)
        .toMatch(/(\.segments\.\d+\.|caption)/);
    }
  });

  it("has exactly as many Spanish strings as English ones", () => {
    expect(facts.i18n.es).toBe(facts.i18n.en);
  });

  it("counts Playwright tests, which use test() and not it()", () => {
    // The defect this replays: `it(` matched zero of the 87 Playwright tests, so the
    // validation report would have claimed no browser coverage existed.
    const specs = readdirSync("tests/visual").filter((f) => f.endsWith(".spec.ts"));
    expect(facts.validation.e2eSpecFiles).toBe(specs.length);
    const counted = specs.reduce(
      (a, f) => a + (readFileSync(`tests/visual/${f}`, "utf8").match(/^\s*(?:it|test)\(/gm) || []).length, 0);
    expect(facts.validation.e2eTests).toBe(counted);
    expect(facts.validation.e2eTests).toBeGreaterThan(0);
  });

  it("counts the validators the verify script actually runs", () => {
    const pkg = JSON.parse(readFileSync("package.json", "utf8"));
    const steps = (name: string) => pkg.scripts[name].split("&&").map((s: string) => s.trim()).filter(Boolean);
    // A validator and a chain step are not the same thing. `content:check` runs
    // gen-glossary.cjs before check-glossary.cjs so the measured usage counts cannot be
    // stale, and counting that generator as a validator reported 12 gates where 11
    // exist — a number that would have gone into STATUS.md and validation-report.md as
    // evidence. Both are asserted, and the generator is required to be excluded.
    const chain = steps("content:check");
    const generators = chain.filter((s: string) => s.includes("/gen-"));
    expect(facts.validation.contentCheckSteps).toBe(chain.length);
    expect(facts.validation.contentValidators).toBe(chain.length - generators.length);
    expect(generators.length, "a generator in content:check is being counted as a gate")
      .toBeGreaterThan(0);
    expect(facts.validation.selfTests).toBe(steps("gates:selftest").length);
    expect(facts.validation.verifySteps).toBe(steps("verify").length);
  });
});


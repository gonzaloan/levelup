const facts = JSON.parse(readFileSync(`${DOCS}/facts.json`, "utf8"));
const CONCEPT_LESSONS = LESSONS.flatMap((l) => l.concepts);
/** A newline as a binding — see the same note in tools/gen-docs.cjs. */
const NL = String.fromCharCode(10);


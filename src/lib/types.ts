export type Locale = "en" | "es";
export type I18n = { en: string; es: string };
export type Level = "core" | "advanced" | "staff";

export interface Domain {
  id: string;
  icon: string;
  title: I18n;
  tagline: I18n;
  concepts: string[];
}

export interface Concept {
  id: string;
  domain: string;
  level: Level;
  title: I18n;
  aliases: string[];
  tldr: I18n;
  analogy?: I18n;
  explain: I18n;
  diagram?: { code: string; caption: I18n };
  code?: { lang: string; title: I18n; source: string };
  example: I18n;
  deepDive?: { title: I18n; body: I18n }[];
  pros: I18n[];
  cons: I18n[];
  whenToUse: I18n;
  whenNotToUse: I18n;
  numbers?: I18n[];
  pitfalls: I18n[];
  interview: { q: I18n; a: I18n }[];
  related: string[];
  sources: { title: string; url: string }[];
}

/** Client-side search record (generated by tools/build-content.mjs). */
export interface SearchDoc {
  id: string;
  d: string; // domain
  l: Level;
  t: string; // title (current locale)
  o: string; // title (other locale)
  a: string; // aliases
  s: string; // tldr
  b: string; // explanation (plain, truncated)
  q: string; // interview questions
}

/** Practice card (generated). */
export interface QADoc {
  k: string; // stable key: conceptId#index
  id: string;
  d: string;
  t: string;
  q: string;
  a: string;
}
